/**
 * The Tungaamal → Unicode rewrite table.
 *
 * GENERATED from a measurement, not written by hand — see "Where this came
 * from" below. Edit the measurement and regenerate; a row edited here has no
 * proof behind it.
 *
 * ## What Tungaamal text is
 *
 * The Tungaamal convention is Mongolia's dominant bichig keyboard and font family. Its text
 * sits in the standard Mongolian block with no PUA, which is why it is easy to
 * mistake for Unicode, and it is not: read out of the fonts' own GSUB tables,
 * the convention is
 *
 * - **two extra letters.** U+1889 is feminine g and U+1888 feminine k/h. The
 *   fonts do no gender shaping at all — U+182C/U+182D are always drawn
 *   masculine — so the writer picks the gender by picking the letter;
 * - **one selector, used as a toggle.** FVS1 means "the other form of this
 *   letter here"; FVS2 and FVS3 draw an INVALID mark. That is not the
 *   pre-2020 Unicode model and not the current one: the same bytes select a
 *   different written form in six contexts (rows below marked
 *   `the Tungaamal convention FVS1, standard FVS2/FVS3`);
 * - **no connector shaping.** NNBSP is a blank, and what follows is shaped as
 *   a new word. A suffix gets its suffix form only from an FVS1 on its first
 *   letter — so those selectors are load-bearing in the Tungaamal convention and must go
 *   once the suffix is joined by MVS, where the standard shapes it by itself;
 * - **MVS only before a detached final a/e.**
 *
 * ## The three kinds
 *
 * - `encoding` — the two conventions write the same written form with
 *   different (or the same) code points. Always applied.
 * - `tungaamal-defect` — the text, as its own fonts draw it, shows a typist's
 *   slip or a font quirk. The row reproduces the PICTURE; `intended` says what
 *   plain standard text draws instead. Applied in faithful mode; in the
 *   default mode only the few `tungaamal.ts` names, and it says why.
 * - `no-equivalent` — the Tungaamal face draws a form no standard sequence
 *   draws. The row is the nearest plain spelling.
 *
 * For each letter the FIRST row whose conditions hold is applied, so order is
 * part of the data.
 *
 * ## Where this came from, and what it is proven against
 *
 * Measured 2026-10-02 by shaping with HarfBuzz: the left side with the
 * Tungaamal faces (two of them, which shape identically over 631,266 probe
 * strings), the right with Noto Sans Mongolian, both glyph runs reduced to
 * written forms (unit + position) and compared. Over 9,686 distinct tokens
 * (180,138 occurrences) from 714 public pages typed in the Tungaamal convention
 * convention, the full table reproduces the Tungaamal picture on 9,662 tokens
 * against Noto 3.002.
 *
 * The same 9,662 hold against the hinted Noto 3.100 build, the face this
 * project pins for review.
 *
 * ⚠ **Not every 3.100 build.** The release's `full` and `googlefonts` builds
 * draw plain U+182C/U+182D differently from `hinted`, `unhinted` and 3.002 —
 * gender from the vowel before the letter only, no dotted default for a medial
 * gh — so `mongγul` gets a feminine g and `qaγan` an undotted gh, and 2,503 of
 * the 9,133 words of this package's own lexicon change written form. That is a
 * fault in those builds, not a change in the model, and nothing here
 * compensates for it. `docs/tungaamal.md` has the table.
 *
 * Code points are numbers throughout; this file contains no literal invisible
 * character.
 */

export type TungaamalRuleKind = 'encoding' | 'tungaamal-defect' | 'no-equivalent';

/** Where a letter stands among the letters of its run. */
export type Place = 'isol' | 'init' | 'medi' | 'fina';

/** A selector as the table names it. Tungaamal text only ever has FVS1. */
export type Selector = 'none' | 'FVS1' | 'FVS2' | 'FVS3';

/** A named set of letters, or one code point. `start`/`end`: no neighbour. */
export type LetterClass =
  | number
  | 'vowel'
  | 'vowelNotI'
  | 'masculineVowel'
  | 'feminineVowel'
  | 'frontOrI'
  | 'bowed'
  | 'consonant'
  | 'start'
  | 'end';

/** What stands before or after a run: a code point, or the edge of the text. */
export type RunEdge = number | 'start' | 'end';

export interface TungaamalRule {
  id: string;
  kind: TungaamalRuleKind;
  /** The Tungaamal convention letter(s) the row is about. */
  letters: readonly number[];
  /** The selector on the letter in the Tungaamal text. */
  selector?: Selector;
  place?: readonly Place[];
  next?: readonly LetterClass[];
  prev?: readonly LetterClass[];
  prevNot?: readonly LetterClass[];
  nextNot?: readonly LetterClass[];
  prevPrev?: readonly LetterClass[];
  nextPlace?: readonly Place[];
  prevPlace?: readonly Place[];
  prevSelector?: Selector;
  nextSelector?: Selector;
  /** Fails when the previous letter is one of these AND carries a selector. */
  prevSelectorNotOn?: readonly number[];
  /** The next letter is the same letter. */
  sameAsNext?: boolean;
  /** A ZWJ stands between the previous letter and this one. */
  afterZwj?: boolean;
  /** The letter is (or is not) the first of its run. */
  first?: boolean;
  /** Position among the letters of the run, 0-based. */
  index?: number;
  minIndex?: number;
  runLength?: number;
  runAfter?: readonly RunEdge[];
  runAfterNot?: readonly RunEdge[];
  runBefore?: readonly RunEdge[];
  runBeforeNot?: readonly RunEdge[];
  /** The letter after the MVS that follows the run. */
  afterMvsLetter?: readonly LetterClass[];
  /** The run stands after NNBSP and its letters are one of the standard's particles. */
  particle?: boolean;
  /** No vowel stands before the letter in its run. */
  noVowelBefore?: boolean;
  /** Negated "the Tungaamal convention draws the extra tooth here by itself" — see `tungaamal.ts`. */
  tungaamalNoTooth?: boolean;
  /** How the standard would decide the gender of a q/gh here — see `tungaamal.ts`. */
  masculineContext?: boolean;
  out: { letter?: number; selector?: Selector; delete?: true };
  note: string;
  /** For a `tungaamal-defect` row: what plain standard text draws instead. */
  intended?: string;
}

